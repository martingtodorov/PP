/** Admin-editable routing (origin / URL prefix / homepage path per locale).
 *  Overridden at runtime from GET /api/locales so the shop owner can change
 *  domains, language prefixes and homepage URLs from the admin panel. */
export const applyLocaleRoutes = (routes) => {
  if (!routes) return;
  Object.entries(routes).forEach(([loc, cfg]) => {
    if (!LOCALE_META[loc]) return;
    if (cfg.origin) LOCALE_META[loc].origin = cfg.origin;
    if (cfg.prefix !== undefined) LOCALE_META[loc].prefix = cfg.prefix;
    LOCALE_META[loc].home_path = cfg.home_path || "/";
    LOCALE_META[loc].enabled = cfg.enabled !== false;
  });
};

